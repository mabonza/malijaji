-- Respondents (anonymous visitors) may only ADD responses; they can never read, change or delete them.
-- You view and export the data from the Supabase dashboard, which bypasses these rules.
alter table public.responses enable row level security;

drop policy if exists "anyone can submit a response" on public.responses;
create policy "anyone can submit a response"
  on public.responses for insert
  to anon
  with check (true);
